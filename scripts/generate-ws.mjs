// Generates zod schemas and types for the WebSocket messages from contracts/ws (Part 8 §9.2, decision 0029 #1).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { jsonSchemaToZod } from "json-schema-to-zod";

const CONTRACTS = "contracts/ws";
const OUTPUT = "src/shared/ws/generated/messages.ts";

const files = Object.fromEntries(
  readdirSync(CONTRACTS)
    .filter((file) => file.endsWith(".schema.json"))
    .map((file) => [file, JSON.parse(readFileSync(join(CONTRACTS, file), "utf8"))]),
);

// json-schema-to-zod does not follow $ref, so every reference is inlined first.
const resolve = (node, file) => {
  if (Array.isArray(node)) return node.map((item) => resolve(item, file));
  if (node === null || typeof node !== "object") return node;
  if (typeof node.$ref === "string") {
    const [target, pointer] = node.$ref.split("#");
    const targetFile = target === "" ? file : target;
    const name = pointer.replace("/$defs/", "");
    const { $ref: _ref, ...rest } = node;
    return { ...resolve(files[targetFile].$defs[name], targetFile), ...resolve(rest, file) };
  }
  return Object.fromEntries(
    Object.entries(node).map(([key, value]) => [key, resolve(value, file)]),
  );
};

const pascal = (name) => name[0].toUpperCase() + name.slice(1);

const generateGroup = (file, group) => {
  const union = `${group}Message`;
  const names = Object.keys(files[file].$defs);
  const parts = names.map((name) =>
    jsonSchemaToZod(resolve(files[file].$defs[name], file), {
      module: "esm",
      name: `${name}${pascal(group)}MessageSchema`,
      type: `${pascal(name)}${pascal(group)}Message`,
      noImport: true,
    }),
  );
  const members = names.map((name) => `${name}${pascal(group)}MessageSchema`).join(", ");
  return [
    ...parts,
    `export const ${union}Schema = z.discriminatedUnion("t", [${members}]);`,
    `export type ${pascal(union)} = z.infer<typeof ${union}Schema>;`,
  ].join("\n\n");
};

writeFileSync(
  OUTPUT,
  [
    "// Generated by scripts/generate-ws.mjs from contracts/ws — do not edit.",
    'import { z } from "zod";',
    generateGroup("client.schema.json", "client"),
    generateGroup("server.schema.json", "server"),
  ].join("\n\n") + "\n",
);
